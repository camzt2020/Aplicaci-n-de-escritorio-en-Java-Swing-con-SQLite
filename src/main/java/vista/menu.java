    private void abrirPreguntas() {
        abrirPreguntas(false);
    }

    private void abrirPreguntas(boolean soloMias) {
        if (!sesion.haySesion()) {
            JOptionPane.showMessageDialog(this, "Tu sesión no está activa. Vuelve a iniciar sesión.");
            return;
        }
        new PreguntasVista(soloMias).setVisible(true);
    }

    private void seleccionarPregunta() {
        java.util.List<preguntas> preguntas;
        try {
            preguntas = new preguntas_DB().obtenerPreguntas();
        } catch (RuntimeException ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(), "Error al cargar preguntas", JOptionPane.ERROR_MESSAGE);
            return;
        }
        if (preguntas.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Todavía no hay preguntas publicadas.");
            return;
        }
        Object seleccion = JOptionPane.showInputDialog(this, "Selecciona una pregunta:",
                "Preguntas del foro", JOptionPane.QUESTION_MESSAGE, null,
                preguntas.toArray(), preguntas.get(0));
        if (seleccion instanceof preguntas pregunta) {
            new RespuestasVista(pregunta).setVisible(true);
        }
    }

