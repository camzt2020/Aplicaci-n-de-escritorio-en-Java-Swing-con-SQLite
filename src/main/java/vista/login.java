    private void BTiniciarsesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTiniciarsesionActionPerformed
        String correo = Txtincorreo.getText().trim();
        String clave = new String(Txtinclave.getPassword());
        if (correo.isEmpty() || clave.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingresa correo y clave.", "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        user usuario = new user_DB().iniciarSesion(correo, clave);
        if (usuario == null) {
            JOptionPane.showMessageDialog(this, "Correo o clave incorrectos.", "No se pudo iniciar sesión", JOptionPane.ERROR_MESSAGE);
            return;
        }
        sesion.iniciarSesion(usuario.getIdUsuario(), usuario.getNombre());
        new menu().setVisible(true);
        dispose();
    }//GEN-LAST:event_BTiniciarsesionActionPerformed

