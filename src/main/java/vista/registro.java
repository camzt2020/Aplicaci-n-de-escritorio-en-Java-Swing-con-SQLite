    private void registrarUsuario() {
        String nombre = txtNombre.getText().trim();
        String correo = txtCorreo.getText().trim();
        String password = new String(txtPassword.getPassword());

        if (nombre.isEmpty() || correo.isEmpty() || password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Completa todos los campos.",
                    "Datos incompletos", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (!correo.matches("^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$")) {
            JOptionPane.showMessageDialog(this, "Escribe un correo válido.",
                    "Correo inválido", JOptionPane.WARNING_MESSAGE);
            txtCorreo.requestFocus();
            return;
        }
        if (password.length() < 6) {
            JOptionPane.showMessageDialog(this, "La clave debe tener al menos 6 caracteres.",
                    "Clave muy corta", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            boolean registrado = new user_DB().registrarUsuario(nombre, correo, password);
            if (registrado) {
                JOptionPane.showMessageDialog(this, "Cuenta creada. Ya puedes iniciar sesión.",
                        "Registro exitoso", JOptionPane.INFORMATION_MESSAGE);
                txtNombre.setText("");
                txtCorreo.setText("");
                txtPassword.setText("");
                dispose();
                new login().setVisible(true);
            }
        } catch (SQLException ex) {
            String detalle = ex.getMessage() == null ? "" : ex.getMessage();
            String mensaje = (ex.getErrorCode() == 19 || detalle.toLowerCase().contains("unique"))
                    ? "Ese correo ya está registrado. Prueba con otro."
                    : "No se pudo guardar el usuario en SQLite.\nDetalle: " + detalle;
            JOptionPane.showMessageDialog(this, mensaje, "Error de registro", JOptionPane.ERROR_MESSAGE);
        }
    }

